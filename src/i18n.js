// Simple {placeholder} interpolation
export const t = (str, vars = {}) =>
  str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));

// "YYYY-MM" → localized "March 2026"
export const monthLabel = (ym, locale) => {
  const [y, m] = ym.split('-').map(Number);
  return new Date(y, m - 1, 1).toLocaleDateString(locale, { month: 'long', year: 'numeric' });
};

export const fmtMoney = (n, currency, lang) => {
  const s = S[lang];
  const num = Number(n).toLocaleString(s.locale);
  return `${num} ${s.currencies[currency] || currency}`;
};
